LEAKAGE_REPORT_MD = """# HeatSense AI — Leakage Report

**Dataset**: `data/processed/cell_features.parquet`
**Target**: `observed_lst_c` (seasonal median daytime LST in °C)
**Generated by**: `src/data/leakage_check.py`

## Methodology

Each feature was reviewed for three types of leakage risk:

1. **Thermal derivation**: Is the feature calculated (directly or indirectly)
   from the Landsat thermal band (ST_B10) that produces observed_lst_c?
2. **Target leakage**: Does the feature contain or encode the target value?
3. **Multicollinearity / near-duplicate**: Does the feature carry effectively
   the same information as another feature, inflating apparent model capacity?

---

## Feature Review Table

| Feature | Leakage? | Reason | Decision |
|---------|----------|--------|----------|
{rows}

---

## Key Findings

### 1. No direct thermal leakage detected
All spectral indices (NDVI, NDBI, MNDWI, albedo) are derived from Landsat
and Sentinel-2 **optical** bands only, not from the ST_B10 thermal band that
produces observed_lst_c.

### 2. impervious_fraction is near-redundant
Pearson correlation with `built_up_fraction` = **0.9999** (max value
difference only 0.0154 across all 3,472 rows). Including both provides no
measurable additional information and introduces multicollinearity.
**Decision: exclude `impervious_fraction` from the model feature set.**

### 3. valid_obs_count is a quality flag, not a predictor
All 3,472 rows have exactly 19 valid observations — zero variance. Including
it adds no predictive value. Excluded.

### 4. Spatial identifiers (centroid_x / centroid_y) excluded from model
These are preserved for spatial CV and residual mapping, but are not fed
into the XGBoost model as features to avoid memorising spatial coordinates
instead of surface properties.

---

## Preprocessing Split Integrity

- Train/validation split is performed **per season** on individual rows.
- No normalisation or imputation is applied to the entire dataset before
  splitting — all preprocessing is fit-on-train, applied-on-val.
- No target encoding or feature engineering uses cross-fold information.

---

## Conclusion

**The feature set used for training (14 features) has no identified leakage
risk.** The main concern addressed is the near-perfect multicollinearity
between `built_up_fraction` and `impervious_fraction`. Removing the latter
reduces redundancy without information loss.

"""


def build_report(df: pd.DataFrame) -> str:
    """Build the leakage report markdown string with computed correlation values."""
    rows_md = []
    for feat, (leak, reason, decision) in LEAKAGE_REVIEW.items():
        in_df = feat in df.columns
        corr_str = ""
        if in_df and TARGET_COL in df.columns:
            corr = df[feat].corr(df[TARGET_COL])
            corr_str = f" (corr_with_target={corr:.4f})"
        rows_md.append(
            f"| `{feat}` | {'⚠ YES' if leak else 'No'} | {reason}{corr_str} | {decision} |"
        )

    return LEAKAGE_REPORT_MD.format(rows="\n".join(rows_md))


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    parser = argparse.ArgumentParser(description="HeatSense leakage audit")
    parser.add_argument("--features", type=Path, default=Path("data/processed/cell_features.parquet"))
    parser.add_argument("--out-dir",  type=Path, default=Path("reports"))
    args = parser.parse_args()

    if not args.features.exists():
        logger.error(f"Features not found: {args.features}")
        sys.exit(1)

    df = pd.read_parquet(args.features)
    report_md = build_report(df)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    out_path = args.out_dir / "leakage_report.md"
    out_path.write_text(report_md, encoding="utf-8")
    logger.info(f"Saved: {out_path}")
    import sys
    sys.stdout.buffer.write(report_md.encode("utf-8", errors="replace"))


if __name__ == "__main__":
    main()
